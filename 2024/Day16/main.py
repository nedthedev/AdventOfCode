class Grid:
	def __init__(self, data):
		self.start = None
		self.end = None
		self.map = self.gen(data)

	def gen(self, data):
		map = []
		for r, row in enumerate(data):
			map.append([])
			for c, symbol in enumerate(row):
				cell = Cell(r, c, symbol)
				if(symbol == "E"):
					self.end = cell
				elif(symbol == "S"):
					self.start = cell
					self.start.parent = map[cell.y][cell.x-1]
					# self.start.parent = self.start
					self.start.weight = 0
				map[len(map)-1].append(cell)
		for row in map:
			for c in row:
				c.find_neighbors(map)
		return map
	
	def solve(self):
		queue = [self.start]
		while(len(queue) > 0):
			# self.print()
			current = queue.pop()
			for n in current.neighbors:
				if(current.parent.y == n.y or current.parent.x == n.x):
					if(current.weight + n.cost < n.weight):
						n.weight = current.weight + n.cost
						n.parent = current
						queue.append(n)
				else:
					if(current.weight + n.cost +1000 < n.weight):
						n.weight = current.weight + n.cost + 1000
						n.parent = current
						queue.append(n)

	def print(self):
		for row in self.map:
			s = ''
			for cell in row:
				s += str(f"{cell.weight%10}")
				# s += cell.symbol
			print(s)
		print()

class Cell:
	def __init__(self, row, col, symbol, cost=1):
		self.y, self.x = row, col
		self.symbol = symbol
		self.cost = cost
		self.weight = 100000
		self.paths = []
		self.parent = None
		self.neighbors = []

	def find_neighbors(self, map):
		neighbors = [[-1,0], [0,1], [1,0], [0,-1]]
		nY = nX = 0
		for neighbor in neighbors:
			nY, nX = self.y + neighbor[0], self.x + neighbor[1]
			if(nY >= 1 and nY < len(map)-1 and nX >= 1 and nX < len(map[0])-1 and map[nY][nX].symbol != '#'):
				self.neighbors.append(map[nY][nX])

